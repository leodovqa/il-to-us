function calcFemaSeverity(h, totalDecl) {
  const weighted =
    (h.flood.score * 0.25 +
      h.tornado.score * 0.22 +
      h.hurricane.score * 0.18 +
      h.wildfire.score * 0.15 +
      h.winter_ice.score * 0.12 +
      h.earthquake.score * 0.08) *
    0.8 +
    Math.min(20, totalDecl * 0.65);
  return Math.round(Math.min(100, Math.max(1, weighted)));
}

